            {
              'id': 'bad-outside',
              'created_at': '2026-11-24T12:00:00Z',
              'amphoe_th': 'รามัน',
              'report_type': 'water_rising',
              'lat': 13.75,
              'lon': 100.50,
              'trust_score': 3,
